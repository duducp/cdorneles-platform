#!/usr/bin/env node
// Builds one app and restructures the output into the layout Appwrite Sites'
// SSR runner expects.
//
// Why this exists: Appwrite's SSR bundler runs from the build root and assumes
// a single Next.js project there — it looks for `next.config.*` at the root and
// boots `.next/standalone/server.js`. A monorepo breaks both assumptions:
//
//   - building only `apps/<app>` leaves the pnpm workspace and lockfile behind,
//     so the shared packages cannot resolve;
//   - building from the repository root nests the standalone server at
//     `.next/standalone/apps/<app>/server.js`, where Appwrite cannot find it.
//
// So we build from the root (workspace intact) and then flatten the result.
//
// Usage: node scripts/build-appwrite-site.mjs <app>

import { spawnSync } from "node:child_process";
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const APPS = {
  admin: "@cdorneles/admin",
  client: "@cdorneles/client",
  customer: "@cdorneles/customer",
  "design-system": "@cdorneles/design-system",
};

const app = process.argv[2];
if (!app || !APPS[app]) {
  console.error(`usage: node scripts/build-appwrite-site.mjs <${Object.keys(APPS).join("|")}>`);
  process.exit(1);
}

const root = process.cwd();
const appDir = path.join(root, "apps", app);
const appNext = path.join(appDir, ".next");
const standaloneSrc = path.join(appNext, "standalone");
const outRoot = path.join(root, ".next");
const out = path.join(outRoot, "standalone");

console.log(`[appwrite-site] building ${APPS[app]}`);
const build = spawnSync("pnpm", ["--filter", APPS[app], "build"], {
  stdio: "inherit",
  shell: process.platform === "win32",
});
if (build.status !== 0) {
  console.error("[appwrite-site] build failed");
  process.exit(build.status ?? 1);
}

if (!existsSync(standaloneSrc)) {
  console.error(
    `[appwrite-site] ${path.relative(root, standaloneSrc)} not found — ` +
      `does ${app}'s next.config enable output: "standalone"?`,
  );
  process.exit(1);
}

console.log("[appwrite-site] restructuring output for Appwrite");
await rm(outRoot, { recursive: true, force: true });
await mkdir(out, { recursive: true });

// The traced server and its node_modules.
await cp(standaloneSrc, out, { recursive: true });

// Client bundles, served from .next/static next to the server.
const staticSrc = path.join(appNext, "static");
if (existsSync(staticSrc)) {
  await cp(staticSrc, path.join(out, "apps", app, ".next", "static"), { recursive: true });
}

// Public assets, served alongside the server.
const publicSrc = path.join(appDir, "public");
if (existsSync(publicSrc)) {
  await cp(publicSrc, path.join(out, "apps", app, "public"), { recursive: true });
}

// Appwrite's SSR bundler moves next.config.* from the build root, so provide a
// self-contained copy there. The app's own config imports ../../tooling, which
// would not resolve from the root, so this one is intentionally minimal.
await writeFile(
  path.join(root, "next.config.mjs"),
  "// Generated by scripts/build-appwrite-site.mjs for Appwrite Sites.\nexport default {};\n",
);

// Entry point Appwrite boots: delegate to the real (nested) server.
await writeFile(path.join(out, "server.js"), `require("./apps/${app}/server.js");\n`);

console.log(`[appwrite-site] ready: .next/standalone (app: ${app})`);
